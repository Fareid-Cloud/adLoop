// علامة AdLoop - مصدر الشعار الوحيد في المنتج.
//
// **ما كان:** الشعار مرسوم بالكود في مكانين مختلفين - أيقونة `ListChecks`
// داخل مربّع أزرق في الشريط الجانبيّ، وحرف «A» مكتوب نصّاً في شاشات الحساب.
// وفي `public/` شعار حقيقيّ لا يستعمله شيء. يعني: تعديل ملفّ الشعار لا
// يغيّر شيئاً في الواجهة، والعلامتان المرسومتان لا تتطابقان أصلاً.
//
// **القاعدة:** الشعار ملفّ لا كود. استبدال `BRAND_MARK_SRC` في `public/`
// يغيّر العلامة في المنتج كلّه فوراً - بلا لمس سطر واحد هنا.

/** ملفّ الشعار. استبدله في `public/` ليتغيّر أينما ظهرت العلامة. */
export const BRAND_MARK_SRC = "/icon-192.png";

export function BrandMark({
  size = 28,
  className = "",
}: {
  size?: number;
  className?: string;
}) {
  return (
    // `<img>` عاديّ لا `next/image`: الأخير يخزّن نسخةً محسَّنةً بمفتاحٍ لا
    // يتغيّر بتغيّر الملفّ، فيبقى الشعار القديم معروضاً بعد استبداله - وهو
    // نقيض الغرض من هذا المكوّن. وهو أيضاً نمط المشروع القائم في كلّ الصور.
    //
    // الزوايا الدائرية هنا لا في الملفّ: شعار مربّع يُستبدَل لاحقاً يأخذ
    // الشكل نفسه بلا تعديل، والملفّ الحاليّ زواياه شفّافة فلا يُقصّ منه شيء.
    <img
      src={BRAND_MARK_SRC}
      alt="AdLoop"
      width={size}
      height={size}
      style={{ width: size, height: size }}
      className={`shrink-0 rounded-[8px] object-contain ${className}`}
    />
  );
}
