// رأس الصفحة - الهوية البصرية المشتركة لكلّ صفحة داخل اللوحة.
//
// **ما كان:** ثلاثون صفحة تفتح باسم مساحة العمل، ثمّ `<h1>` عارٍ، ثمّ سطر
// رمادي صغير - ثمّ جدول. لا أيقونة ولا لون ولا أيّ شيء يفرّق صفحة عن أخرى.
// المستخدم ينتقل بين خمس صفحات فتبدو له الخمس صفحةً واحدةً تغيّر محتواها،
// ولا يعرف أين هو إلا بقراءة العنوان في كلّ مرّة.
//
// **الأيقونة ليست زينة:** مربّع ملوّن ثابت لكلّ صفحة هو ما يجعلها تُميَّز
// من طرف العين قبل قراءة كلمة - وهذا بالضبط ما يفعله شريط التنقّل الجانبي
// بالفعل، فالصفحة تكرّر أيقونتها لا تخترع واحدة.
//
// **اللون دلاليّ لا عشوائيّ:** يتبع `tone` - محايد للاستكشاف، تحذيريّ لصفحة
// تعرض مشكلة، متحقَّق لصفحة تعرض ما تأكّد. هذا هو الفرق عن قوالب SaaS التي
// تلوّن لتُبهج.

import type { LucideIcon } from "lucide-react";

export type HeaderTone = "neutral" | "accent" | "verified" | "gap" | "critical";

const TONE: Record<HeaderTone, string> = {
  neutral: "bg-text-muted/10 text-text-muted",
  accent: "bg-accent/12 text-accent",
  verified: "bg-verified/12 text-verified",
  gap: "bg-gap/12 text-gap",
  critical: "bg-critical/12 text-critical",
};

export function PageHeader({
  icon: Icon,
  tone = "accent",
  eyebrow,
  title,
  description,
  actions,
  iconNode,
}: {
  icon?: LucideIcon;
  /** بديلٌ عن `icon` حين تكون العلامة صورةً لا أيقونةً - شعار منصّة مثلاً.
      يُصيَّر داخل المربّع الملوّن نفسه فيبقى الشكل واحداً في كلّ الأقسام. */
  iconNode?: React.ReactNode;
  tone?: HeaderTone;
  /** اسم مساحة العمل عادةً - يجيب «أرقام مَن هذه؟» قبل أن تُقرأ الأرقام */
  eyebrow?: string;
  title: string;
  description?: string;
  /** أزرار الصفحة - تصطفّ مع العنوان لا تحته، فلا تُدفع خارج الشاشة الأولى */
  actions?: React.ReactNode;
}) {
  return (
    // 🔴 ترتيب ثابت لكلّ صفحة في المنتج - وهذا هو الغرض من المكوّن:
    //
    //   اسم مساحة العمل
    //   [أيقونة] العنوان ................... [منتقي الفترة / الأزرار]
    //   الوصف بعرض السطر كاملاً
    //
    // **الوصف خارج العمود الأيسر لا داخله:** حين كان بداخله كان يُحصر في
    // عرض ما تبقّى بعد الأزرار، فينكسر سطراً بعد ثلاث كلمات في صفحة وسطراً
    // واحداً في أخرى - وهو أحد وجهَي الاختلال الذي رآه المالك في «تسعين
    // بالمئة من الأقسام».
    //
    // **والوجه الآخر أنّ منتقي الفترة كان يُصيَّر *بعد* هذا المكوّن** في
    // ثلاث عشرة صفحة، فينزل سطراً مستقلّاً تحت الرأس بدل أن يحاذي العنوان.
    // مكانه الآن `actions` - وهو ما تفعله صفحة «مركز الحقيقة» التي اتّخذها
    // المالك مرجعاً.
    <header className="mb-6">
      {/* 🔴 **اسم المساحة سطرٌ مستقلّ فوق الكلّ، والأيقونة مع العنوان وحده.**
          كانت الأيقونة أختاً للصندوق الذي يضمّ السطرين معاً، فتمتدّ بطولهما
          وتستقرّ **بينهما** - أيقونةٌ لا تخصّ أيّ سطر منهما، وهو ما رآه
          المالك مكسوراً. الآن هي في صفّ العنوان بمحاذاة مركزية، فتُقرأ
          كأيقونة القسم لا كفاصل بين سطرين. */}
      {eyebrow && (
        /* 🔴 **لا `dir` هنا - `bdi` وحده.**
           اسم مساحة عمل عربيّ داخل واجهة إنجليزية كان يُحاذى إلى الجهة
           المقابلة للعنوان تحته، فيبدو السطران غير مرتبطين. عولج بـ
           `dir="ltr"` على الصندوق - وهذا **كسر الواجهة العربية كلّها**:
           `dir` يثبّت معنى `text-start` عند اليسار، فصار اسم المساحة في
           أقصى اليسار والعنوان تحته في أقصى اليمين في كلّ صفحة عربية.
           قِيس فعلياً في متصفّح: ١٥٢px مقابل ١٠٧٢px.
           `bdi` وحده يعزل النصّ فتبقى قراءته الداخلية صحيحة بلغته،
           ومحاذاة الصندوق تتبع اتّجاه الصفحة كما يجب. */
        <div className="mb-1.5 truncate text-start text-[12.5px] text-text-muted">
          <bdi>{eyebrow}</bdi>
        </div>
      )}

      <div className="flex flex-wrap items-center justify-between gap-x-4 gap-y-3">
        <div className="flex min-w-0 items-center gap-3">
          {(Icon || iconNode) && (
            <span
              className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${TONE[tone]}`}
              aria-hidden
            >
              {Icon ? <Icon size={19} /> : iconNode}
            </span>
          )}
          <h1 className="page-title min-w-0">{title}</h1>
        </div>
        {/* `items-center` لا `items-start`: منتقي الفترة زرٌّ بارتفاعٍ قريب
            من ارتفاع العنوان، فمحاذاته بالأعلى تتركه معلّقاً فوق خطّ العنوان. */}
        {actions && <div className="flex shrink-0 flex-wrap items-center gap-2">{actions}</div>}
      </div>

      {description && (
        <p className="mt-2.5 max-w-3xl text-[13px] leading-relaxed text-text-muted">{description}</p>
      )}
    </header>
  );
}
