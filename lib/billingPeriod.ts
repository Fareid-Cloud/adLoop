// lib/billingPeriod.ts
//
// **الفترة ثلاثون يوماً بالضبط - لا «نفس اليوم من الشهر القادم».**
//
// قرارُ المالك صريح: يُشترى ثلاثون يوماً، فتنتهي بعد ثلاثين يوماً بالثانية،
// أيّاً كان الشهر وعدد أيّامه. وهو ما تفعله اشتراكاتٌ كثيرة يعرفها الناس،
// وأهمُّ ما فيه أنّه **قابلٌ للحساب**: من اشترك اليوم يعرف متى ينتهي بلا
// أن يسأل كم يوماً في هذا الشهر.
//
// 🔴 وما قبله كان تقويمياً، وله عيبان أُصلح أوّلُهما وبقي الثاني:
//
//   • `setMonth(+1)` كان **يتخطّى شهراً** في نهايات الشهور: ٣١ يناير تصير
//     «٣١ فبراير» فتُقرأ ٣ مارس - واحدٌ وثلاثون يوماً مجّاناً، وموعدٌ يزحف
//     إلى الأمام كلّ دورة.
//   • ثمّ صار يُقصَّر إلى آخر يومٍ حقيقيّ، فاستقام الحساب - لكنّ طول
//     الفترة بقي متذبذباً بين ٢٨ و٣١ يوماً بحسب الشهر: يدفع المشترك
//     المبلغ نفسه ويأخذ في فبراير ثلاثة أيّامٍ أقلّ ممّا يأخذه في مارس.
//
// والثلاثون الثابتة تُنهي الاثنين معاً: لا شهر يُتخطّى، ولا فترةٌ أقصر من
// أختها بالثمن نفسه.
//
// والسنويّ ٣٦٥ يوماً بالمنطق نفسه. والكبيسةُ لا تُستثنى: يومٌ واحدٌ في
// أربع سنين لا يستحقّ فرعاً في مسار الفوترة.

export type BillingCycleName = "monthly" | "yearly";

/** أيّامُ الدورة - رقمان صريحان لا حسابٌ تقويميّ. */
export const CYCLE_DAYS: Record<BillingCycleName, number> = {
  monthly: 30,
  yearly: 365,
};

const DAY_MS = 86_400_000;

/**
 * نهايةُ الفترة التالية ابتداءً من `from`.
 *
 * الوقتُ من اليوم يبقى كما هو، فمن اشترك ٣:٠٠ عصراً تنتهي فترتُه ٣:٠٠
 * عصراً - «بالثانية» كما طُلب، لا عند منتصف ليلٍ يُقرَّب إليه.
 */
export function addBillingPeriod(from: Date, cycle: BillingCycleName): Date {
  return new Date(from.getTime() + CYCLE_DAYS[cycle] * DAY_MS);
}
