// دالة مساعدة بتاخد مسار زي "auth.loginTitle" وتديك النص باللغة المطلوبة،
// مع دعم استبدال متغيرات زي {minutes}
export function t(
  locale: Locale,
  path: string,
  vars?: Record<string, string | number>
): string {
  const keys = path.split(".");
  let value: any = dictionary[locale];

  for (const key of keys) {
    value = value?.[key];
  }

  if (typeof value !== "string") {
    console.warn(`Missing translation for path: ${path} (${locale})`);
    return path;
  }

  if (vars) {
    return Object.entries(vars).reduce(
      (str, [key, val]) => str.replace(`{${key}}`, String(val)),
      value
    );
  }

  return value;
}

// بيحدد اللغة من الطلب - أولوية: تفضيل محفوظ للمستخدم، ثم Accept-Language
// header بتاع المتصفح، ثم افتراضي عربي
export function detectLocale(acceptLanguageHeader: string | null): Locale {
  if (!acceptLanguageHeader) return "ar";
  return acceptLanguageHeader.toLowerCase().startsWith("en") ? "en" : "ar";
}

/**
 * يصوغ نصاً أرجعه محرّك تحليلي على شكل مفتاح + متغيّرات.
 *
 * المفتاح الخاص "raw" يمرّر النص كما هو - يلزم للحالات التي يكون فيها
 * النص قادماً من مصدر لا يملك مفتاحاً (رسالة خطأ من منصّة خارجية مثلاً).
 * وجوده صريح أفضل من تسريب نصوص جاهزة عبر بقية المسار بصمت.
 */
export function tText(
  locale: Locale,
  prefix: string,
  item: { key: string; vars?: Record<string, string | number> }
): string {
  if (item.key === "raw") return String(item.vars?.text ?? "");
  return t(locale, `${prefix}.${item.key}`, item.vars);
}

const PLATFORM_KEYS: Record<string, string> = {
  GOOGLE_ADS: "pGoogle",
  META_ADS: "pMeta",
  TIKTOK_ADS: "pTiktok",
  SNAPCHAT_ADS: "pSnapchat",
};

/**
 * اسم المنصة بلغة الواجهة. كان معرَّفاً حرفياً في ستّة ملفات مختلفة، فأي
 * منصة جديدة كانت تتطلّب تعديل ستّة أماكن - نقطة حقيقة واحدة بدلها.
 * أي قيمة غير معروفة تُعاد كما هي بدل إخفائها.
 */
export function platformLabel(locale: Locale, platform: string): string {
  const key = PLATFORM_KEYS[platform];
  return key ? t(locale, `common.${key}`) : platform;
}

/**
 * زمن نسبي بلغة الواجهة. النسخة السابقة (relativeAr) كانت تبني جملة عربية
 * داخل الخادم، فتُقفل اللغة عند لحظة الحساب. هنا يُمرَّر عدد الساعات فقط
 * ويُصاغ النصّ عند العرض.
 */
export function relativeFromHours(locale: Locale, hours: number): string {
  const minutes = Math.max(0, Math.round(hours * 60));
  if (minutes < 1) return t(locale, "integrations.tNow");
  let value: string;
  if (minutes < 60) value = t(locale, "integrations.tMinutes", { n: minutes });
  else if (minutes < 60 * 24) value = t(locale, "integrations.tHours", { n: Math.floor(minutes / 60) });
  else if (minutes < 60 * 24 * 30) value = t(locale, "integrations.tDays", { n: Math.floor(minutes / (60 * 24)) });
  else value = t(locale, "integrations.tMonths", { n: Math.floor(minutes / (60 * 24 * 30)) });
  return t(locale, "integrations.ago", { value });
}

/** المدّة وحدها بلا صيغة "منذ" - تُركَّب داخل جُمل أخرى. */
export function durationFromHours(locale: Locale, hours: number): string {
  const minutes = Math.max(0, Math.round(hours * 60));
  if (minutes < 1) return t(locale, "integrations.tNow");
  if (minutes < 60) return t(locale, "integrations.tMinutes", { n: minutes });
  if (minutes < 60 * 24) return t(locale, "integrations.tHours", { n: Math.floor(minutes / 60) });
  if (minutes < 60 * 24 * 30) return t(locale, "integrations.tDays", { n: Math.floor(minutes / (60 * 24)) });
  return t(locale, "integrations.tMonths", { n: Math.floor(minutes / (60 * 24 * 30)) });
}

/** نفس الشيء انطلاقاً من تاريخ - يُحسب في العميل حتى يبقى دقيقاً بعد التحميل. */
export function relativeFromDate(locale: Locale, date: Date | string | null, now: Date = new Date()): string | null {
  if (!date) return null;
  const d = typeof date === "string" ? new Date(date) : date;
  if (Number.isNaN(d.getTime())) return null;
  return relativeFromHours(locale, (now.getTime() - d.getTime()) / 3_600_000);
}
