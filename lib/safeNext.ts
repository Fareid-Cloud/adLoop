// lib/safeNext.ts
//
// **وجهةُ ما بعد الدخول - داخليّةٌ دائماً.**
//
// `next` بيجي من الرابط، وقبولُه كما هو بيحوّل صفحةَ الدخول لمُحوِّلٍ
// مفتوح (open redirect): رابطٌ شكلُه بتاعنا بيوَدّي لموقعِ تصيّدٍ بعد
// الدخول مباشرةً، والضحيّةُ بتكون لسه كاتبة كلمةَ سرّها فتوّها فتثق
// بالشاشة اللي بعدها.
//
// الفحصُ نفسه كان مكتوباً في `admin-unlock` وحدها؛ وبعد ما بقى مطلوباً
// في التسجيل والدخول والدعوة كمان، اتنقل هنا - نسخةٌ رابعةٌ من فحصِ
// أمانٍ هي أوّلُ نسخةٍ تُنسى.

/** المسارُ الداخليّ وحده. أيُّ حاجةٍ تانية بترجع البديل. */
export function safeNext(raw: string | undefined | null, fallback = "/dashboard"): string {
  if (!raw) return fallback;
  // `//host` بيقراه المتصفّح نطاقاً خارجيّاً ببروتوكولٍ نسبيّ، و`\\` مثله
  // في بعض المتصفّحات - فالاتنين مرفوضان قبل أيّ حاجة.
  if (!raw.startsWith("/") || raw.startsWith("//") || raw.startsWith("/\\")) return fallback;
  // `:` بتمنع `/\t/evil.com` وأشكالَ التحايل اللي بتحمل مخطّطاً.
  if (raw.includes(":")) return fallback;
  return raw;
}
